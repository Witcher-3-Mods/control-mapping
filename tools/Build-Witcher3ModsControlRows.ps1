# Generates the gamepad config matrix and the WitcherScript row table from tools/control-mapping/rows.psd1.
# Run after editing rows.psd1: powershell -NoProfile -ExecutionPolicy Bypass -File tools/Build-Witcher3ModsControlRows.ps1
$ErrorActionPreference = 'Stop'
$Witcher3ModsPackage = Join-Path $PSScriptRoot '../src/modWitcher3ModsControlMapping'
$Witcher3ModsData = Import-PowerShellDataFile -LiteralPath (Join-Path $PSScriptRoot 'control-mapping/rows.psd1')
if ($Witcher3ModsData.StoreGroup -notmatch '^\w+$' -or $Witcher3ModsData.StoreGroup -eq $Witcher3ModsData.Group) { throw 'Invalid StoreGroup.' }
if ($Witcher3ModsData.Version -notmatch '^[0-9.]+$') { throw 'Invalid Version.' }
foreach ($Witcher3ModsKeyName in $Witcher3ModsData.PadKeys) { if ($Witcher3ModsKeyName -notmatch '^IK_Pad_\w+$') { throw "Invalid pad key: $Witcher3ModsKeyName" } }
$Witcher3ModsVars = @{}
foreach ($Witcher3ModsVar in $Witcher3ModsData.Vars) {
    if ($Witcher3ModsVar.Id -notmatch '^W3MPad\w+$') { throw "Invalid var id: $($Witcher3ModsVar.Id)" }
    if ($Witcher3ModsVars.ContainsKey($Witcher3ModsVar.Id)) { throw "Duplicate var id: $($Witcher3ModsVar.Id)" }
    if ($Witcher3ModsVar.Actions -notmatch '^\w+(;\w+)*$') { throw "Invalid actions: $($Witcher3ModsVar.Id)" }
    $Witcher3ModsVars[$Witcher3ModsVar.Id] = $Witcher3ModsVar
}
# =English|Polish labels have no game key; the matrix only needs a readable name for them.
function Get-Witcher3ModsDisplayName([string]$Witcher3ModsLabel) {
    if ($Witcher3ModsLabel.StartsWith('=')) { return $Witcher3ModsLabel.Substring(1).Split('|')[0] }
    return $Witcher3ModsLabel
}
function Get-Witcher3ModsProbe($Witcher3ModsVar) {
    if ($Witcher3ModsVar.Probe) { return $Witcher3ModsVar.Probe }
    return ($Witcher3ModsVar.Actions -split ';')[0]
}
# One stored key per (layout, variable). Its id doubles as the row tag Flash sends back, so the script knows the layout.
function Get-Witcher3ModsStoreId([string]$Witcher3ModsLayoutName, [string]$Witcher3ModsVarId) {
    return 'W3MCtx' + $Witcher3ModsLayoutName + $Witcher3ModsVarId.Substring(6)
}
$Witcher3ModsStoreIds = New-Object 'System.Collections.Generic.List[object]'
$Witcher3ModsSeen = @{}
for ($Witcher3ModsIndex = 0; $Witcher3ModsIndex -lt $Witcher3ModsData.Layouts.Count; $Witcher3ModsIndex++) {
    $Witcher3ModsLayoutName = $Witcher3ModsData.Layouts[$Witcher3ModsIndex].Name
    if ($Witcher3ModsLayoutName -notmatch '^[A-Za-z]+$') { throw "Invalid layout name: $Witcher3ModsLayoutName" }
    foreach ($Witcher3ModsRef in $Witcher3ModsData.Layouts[$Witcher3ModsIndex].Rows) {
        if ($Witcher3ModsRef.StartsWith('@')) { continue }
        if (-not $Witcher3ModsVars.ContainsKey($Witcher3ModsRef)) { throw "Unknown var: $Witcher3ModsRef" }
        $Witcher3ModsId = Get-Witcher3ModsStoreId $Witcher3ModsLayoutName $Witcher3ModsRef
        if ($Witcher3ModsSeen.ContainsKey($Witcher3ModsId)) { throw "A layout lists a variable twice: $Witcher3ModsId" }
        $Witcher3ModsSeen[$Witcher3ModsId] = $true
        $Witcher3ModsStoreIds.Add([pscustomobject]@{ Id = $Witcher3ModsId; Layout = $Witcher3ModsIndex; Var = $Witcher3ModsRef })
    }
}

$Witcher3ModsXml = New-Object 'System.Collections.Generic.List[string]'
$Witcher3ModsXml.Add('<?xml version="1.0" encoding="UTF-8"?>')
$Witcher3ModsXml.Add('<!-- Generated by tools/Build-Witcher3ModsControlRows.ps1 from tools/control-mapping/rows.psd1. -->')
$Witcher3ModsXml.Add('<UserConfig>')
$Witcher3ModsXml.Add("`t" + '<Group builder="Input" id="' + $Witcher3ModsData.Group + '" displayName="controls_pc" tags="keybinds">')
$Witcher3ModsXml.Add("`t`t<VisibleVars>")
foreach ($Witcher3ModsVar in $Witcher3ModsData.Vars) {
    $Witcher3ModsXml.Add("`t`t`t" + '<Var builder="Input" id="' + $Witcher3ModsVar.Id + '" displayName="' + (Get-Witcher3ModsDisplayName $Witcher3ModsVar.Label) + '" displayType="INPUTPAD" actions="' + $Witcher3ModsVar.Actions + '"/>')
}
$Witcher3ModsXml.Add("`t`t</VisibleVars>")
$Witcher3ModsXml.Add("`t</Group>")
# 'keybinds' keeps the group out of the Options menu, like the group above. Values are EInputKey numbers, 0 = not stored yet.
$Witcher3ModsXml.Add("`t" + '<Group id="' + $Witcher3ModsData.StoreGroup + '" displayName="controls_pc" tags="keybinds">')
$Witcher3ModsXml.Add("`t`t<VisibleVars>")
foreach ($Witcher3ModsStore in $Witcher3ModsStoreIds) {
    $Witcher3ModsXml.Add("`t`t`t" + '<Var id="' + $Witcher3ModsStore.Id + '" displayName="' + $Witcher3ModsStore.Id + '" displayType="SLIDER;0;100000;100000"/>')
}
$Witcher3ModsXml.Add("`t`t</VisibleVars>")
$Witcher3ModsXml.Add("`t</Group>")
$Witcher3ModsXml.Add('</UserConfig>')
$Witcher3ModsXmlPath = Join-Path $PSScriptRoot '../src/modWitcher3ModsControlMapping/bin/config/r4game/user_config_matrix/pc/witcher3modscontrolmapping.xml'
New-Item -ItemType Directory -Force (Split-Path $Witcher3ModsXmlPath -Parent) | Out-Null
[IO.File]::WriteAllText($Witcher3ModsXmlPath, (($Witcher3ModsXml -join "`r`n") + "`r`n"), (New-Object Text.UTF8Encoding($false)))

$Witcher3ModsWs = New-Object 'System.Collections.Generic.List[string]'
$Witcher3ModsWs.Add('// Generated by tools/Build-Witcher3ModsControlRows.ps1 from tools/control-mapping/rows.psd1.')
$Witcher3ModsWs.Add('// Edit the data file, then run the generator.')
$Witcher3ModsWs.Add('function Witcher3ModsPadGroup() : name')
$Witcher3ModsWs.Add('{')
$Witcher3ModsWs.Add("    return '" + $Witcher3ModsData.Group + "';")
$Witcher3ModsWs.Add('}')
$Witcher3ModsWs.Add('')
$Witcher3ModsWs.Add('function Witcher3ModsStoreGroup() : name')
$Witcher3ModsWs.Add('{')
$Witcher3ModsWs.Add("    return '" + $Witcher3ModsData.StoreGroup + "';")
$Witcher3ModsWs.Add('}')
$Witcher3ModsWs.Add('')
$Witcher3ModsWs.Add('function Witcher3ModsStoreCount() : int')
$Witcher3ModsWs.Add('{')
$Witcher3ModsWs.Add("    return $($Witcher3ModsStoreIds.Count);")
$Witcher3ModsWs.Add('}')
$Witcher3ModsWs.Add('')
$Witcher3ModsWs.Add('function Witcher3ModsModVersion() : string')
$Witcher3ModsWs.Add('{')
$Witcher3ModsWs.Add('    return "' + $Witcher3ModsData.Version + '";')
$Witcher3ModsWs.Add('}')
$Witcher3ModsWs.Add('')
$Witcher3ModsWs.Add('function Witcher3ModsPadLayoutCount() : int')
$Witcher3ModsWs.Add('{')
$Witcher3ModsWs.Add("    return $($Witcher3ModsData.Layouts.Count);")
$Witcher3ModsWs.Add('}')
$Witcher3ModsWs.Add('')
$Witcher3ModsWs.Add('function Witcher3ModsPadLayoutName(Witcher3ModsLayout : int) : string')
$Witcher3ModsWs.Add('{')
$Witcher3ModsWs.Add('    switch (Witcher3ModsLayout)')
$Witcher3ModsWs.Add('    {')
for ($Witcher3ModsIndex = 0; $Witcher3ModsIndex -lt $Witcher3ModsData.Layouts.Count; $Witcher3ModsIndex++) {
    $Witcher3ModsWs.Add("        case ${Witcher3ModsIndex}: return `"$($Witcher3ModsData.Layouts[$Witcher3ModsIndex].Name)`";")
}
$Witcher3ModsWs.Add('    }')
$Witcher3ModsWs.Add('    return "?";')
$Witcher3ModsWs.Add('}')
$Witcher3ModsWs.Add('')
$Witcher3ModsWs.Add('// Pad key number (EInputKey) back to the enum value; IK_None when the number is not a known pad button.')
$Witcher3ModsWs.Add('function Witcher3ModsPadKeyFromInt(Witcher3ModsKey : int) : EInputKey')
$Witcher3ModsWs.Add('{')
foreach ($Witcher3ModsKeyName in $Witcher3ModsData.PadKeys) {
    $Witcher3ModsWs.Add("    if (Witcher3ModsKey == (int)$Witcher3ModsKeyName) return $Witcher3ModsKeyName;")
}
$Witcher3ModsWs.Add('    return IK_None;')
$Witcher3ModsWs.Add('}')
$Witcher3ModsWs.Add('')
$Witcher3ModsWs.Add('function Witcher3ModsPadRowCount(Witcher3ModsLayout : int) : int')
$Witcher3ModsWs.Add('{')
$Witcher3ModsWs.Add('    switch (Witcher3ModsLayout)')
$Witcher3ModsWs.Add('    {')
for ($Witcher3ModsIndex = 0; $Witcher3ModsIndex -lt $Witcher3ModsData.Layouts.Count; $Witcher3ModsIndex++) {
    $Witcher3ModsWs.Add("        case ${Witcher3ModsIndex}: return $($Witcher3ModsData.Layouts[$Witcher3ModsIndex].Rows.Count);")
}
$Witcher3ModsWs.Add('    }')
$Witcher3ModsWs.Add('    return 0;')
$Witcher3ModsWs.Add('}')
$Witcher3ModsWs.Add('')
$Witcher3ModsWs.Add('// Witcher3ModsVar and Witcher3ModsStore are empty for locked rows; Witcher3ModsProbe is the action whose live pad key is shown.')
$Witcher3ModsWs.Add('function Witcher3ModsPadRow(Witcher3ModsLayout : int, Witcher3ModsRow : int, out Witcher3ModsVar : name, out Witcher3ModsLabel : string, out Witcher3ModsProbe : name, out Witcher3ModsStore : name) : bool')
$Witcher3ModsWs.Add('{')
$Witcher3ModsWs.Add('    Witcher3ModsVar = '''';')
$Witcher3ModsWs.Add('    Witcher3ModsStore = '''';')
$Witcher3ModsWs.Add('    switch (Witcher3ModsLayout * 100 + Witcher3ModsRow)')
$Witcher3ModsWs.Add('    {')
for ($Witcher3ModsIndex = 0; $Witcher3ModsIndex -lt $Witcher3ModsData.Layouts.Count; $Witcher3ModsIndex++) {
    $Witcher3ModsRows = $Witcher3ModsData.Layouts[$Witcher3ModsIndex].Rows
    $Witcher3ModsLayoutName = $Witcher3ModsData.Layouts[$Witcher3ModsIndex].Name
    for ($Witcher3ModsRowIndex = 0; $Witcher3ModsRowIndex -lt $Witcher3ModsRows.Count; $Witcher3ModsRowIndex++) {
        $Witcher3ModsRef = $Witcher3ModsRows[$Witcher3ModsRowIndex]
        $Witcher3ModsCase = $Witcher3ModsIndex * 100 + $Witcher3ModsRowIndex
        if ($Witcher3ModsRef.StartsWith('@')) {
            $Witcher3ModsLocked = $Witcher3ModsData.Locked[$Witcher3ModsRef.Substring(1)]
            if (-not $Witcher3ModsLocked) { throw "Unknown locked row: $Witcher3ModsRef" }
            $Witcher3ModsLine = "        case ${Witcher3ModsCase}: Witcher3ModsLabel = `"$($Witcher3ModsLocked.Label)`"; Witcher3ModsProbe = '$($Witcher3ModsLocked.Probe)'; return true;"
        } else {
            $Witcher3ModsVar = $Witcher3ModsVars[$Witcher3ModsRef]
            $Witcher3ModsLine = "        case ${Witcher3ModsCase}: Witcher3ModsVar = '$($Witcher3ModsVar.Id)'; Witcher3ModsStore = '$(Get-Witcher3ModsStoreId $Witcher3ModsLayoutName $Witcher3ModsVar.Id)'; Witcher3ModsLabel = `"$($Witcher3ModsVar.Label)`"; Witcher3ModsProbe = '$(Get-Witcher3ModsProbe $Witcher3ModsVar)'; return true;"
        }
        $Witcher3ModsWs.Add($Witcher3ModsLine)
    }
}
$Witcher3ModsWs.Add('    }')
$Witcher3ModsWs.Add('    return false;')
$Witcher3ModsWs.Add('}')
$Witcher3ModsWs.Add('')
$Witcher3ModsWs.Add('// Row tag sent by Flash (a stored-key id) back to its layout and group variable.')
$Witcher3ModsWs.Add('function Witcher3ModsStoreLookup(Witcher3ModsStore : name, out Witcher3ModsLayout : int, out Witcher3ModsVar : name) : bool')
$Witcher3ModsWs.Add('{')
$Witcher3ModsWs.Add('    Witcher3ModsLayout = -1;')
$Witcher3ModsWs.Add('    Witcher3ModsVar = '''';')
$Witcher3ModsWs.Add('    switch (Witcher3ModsStore)')
$Witcher3ModsWs.Add('    {')
foreach ($Witcher3ModsStore in $Witcher3ModsStoreIds) {
    $Witcher3ModsWs.Add("        case '$($Witcher3ModsStore.Id)': Witcher3ModsLayout = $($Witcher3ModsStore.Layout); Witcher3ModsVar = '$($Witcher3ModsStore.Var)'; return true;")
}
$Witcher3ModsWs.Add('    }')
$Witcher3ModsWs.Add('    return false;')
$Witcher3ModsWs.Add('}')
$Witcher3ModsWs.Add('')
$Witcher3ModsWs.Add('function Witcher3ModsPadIsVar(Witcher3ModsVar : name) : bool')
$Witcher3ModsWs.Add('{')
$Witcher3ModsWs.Add('    switch (Witcher3ModsVar)')
$Witcher3ModsWs.Add('    {')
foreach ($Witcher3ModsVar in $Witcher3ModsData.Vars) { $Witcher3ModsWs.Add("        case '$($Witcher3ModsVar.Id)': return true;") }
$Witcher3ModsWs.Add('    }')
$Witcher3ModsWs.Add('    return false;')
$Witcher3ModsWs.Add('}')
$Witcher3ModsWsPath = Join-Path $Witcher3ModsPackage 'content/scripts/local/Witcher3ModsControlRows.ws'
New-Item -ItemType Directory -Force (Split-Path $Witcher3ModsWsPath -Parent) | Out-Null
[IO.File]::WriteAllText($Witcher3ModsWsPath, (($Witcher3ModsWs -join "`n") + "`n"), (New-Object Text.UTF8Encoding($false)))
Write-Output "Generated $Witcher3ModsXmlPath and $Witcher3ModsWsPath ($($Witcher3ModsStoreIds.Count) stored keys)"
